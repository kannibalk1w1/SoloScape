#!/usr/bin/env python3
"""Encode three original synthetic tetrahedron models with wasm-model-decode's encode(), from declared designs.

The designs are written here, not taken from decoder output: a closed tetrahedron at +/-400 (outward winding,
so both front and back faces exist from either camera), a copy with one vertex moved +200 on x, and a copy with
one face colour changed. encode() is imported by path from wasm-model-decode/tools and is not modified.

Writes build/fixtures.json (designs, expected arrays, bytes) and build/bridge/BridgeFixtures.java (hex only).
Fails (nonzero) on any encoder rejection, a fixture above 1 KiB, or a design that is not all type-1 faces.
"""
import argparse
import importlib.util
import json
import pathlib
import sys

HERE = pathlib.Path(__file__).resolve().parent.parent
ENCODER = HERE.parent / "wasm-model-decode" / "tools" / "encode_decode_fixtures.py"
MAX_FIXTURE_BYTES = 1024


def die(message):
    print("encode_bridge_fixtures: " + message, file=sys.stderr)
    sys.exit(1)


def load_encoder():
    spec = importlib.util.spec_from_file_location("encode_decode_fixtures", ENCODER)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


BASE_VERTICES = [(400, 400, 400), (400, -400, -400), (-400, 400, -400), (-400, -400, 400)]
# Outward winding: each face normal points away from the origin (the tetrahedron centre).
FACES = [(1, 0, 1, 2), (1, 0, 3, 1), (1, 0, 2, 3), (1, 1, 3, 2)]
COLOURS = [0x8000, 0x0102, 0xF00D, 0x7FFF]


def tetra(name, vertices=BASE_VERTICES, colours=COLOURS):
    return {"name": name, "vertices": list(vertices), "faces": list(FACES), "colours": list(colours), "zeroBits": {}}


DESIGNS = [
    tetra("tetra"),
    # Vertex 0 moved +200 on x (400 -> 600): a visible change on the projected geometry.
    tetra("tetra_vertex", vertices=[(600, 400, 400)] + BASE_VERTICES[1:]),
    # Face 0 colour index changed from 0x8000 to 0x1234 (a different palette entry, not a neighbour).
    tetra("tetra_colour", colours=[0x1234] + COLOURS[1:]),
]


def expected_arrays(encoder, design):
    # The decoder's expected arrays are declared by the encoder's own expected_arrays() from the design.
    return encoder.expected_arrays(design)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--out", required=True)
    args = parser.parse_args()
    out = pathlib.Path(args.out)
    (out / "bridge").mkdir(parents=True, exist_ok=True)
    encoder = load_encoder()

    records = []
    for design in DESIGNS:
        data, _ = encoder.encode(design)
        if len(data) > MAX_FIXTURE_BYTES:
            die(f"{design['name']}: {len(data)} bytes exceeds {MAX_FIXTURE_BYTES}")
        if any(face[0] != 1 for face in design["faces"]):
            die(f"{design['name']}: every face must be type 1")
        records.append({
            "name": design["name"],
            "bytes": len(data),
            "hex": data.hex(),
            "design": {"vertices": design["vertices"], "faces": design["faces"], "colours": design["colours"]},
            "expected": expected_arrays(encoder, design),
        })

    (out / "fixtures.json").write_text(json.dumps(records, indent=2) + "\n", encoding="utf-8")
    lines = ["/* GENERATED by tools/encode_bridge_fixtures.py. Original synthetic designs only. */",
             "final class BridgeFixtures {",
             "    static final String[] NAMES = {"]
    lines += [f"        \"{r['name']}\"," for r in records]
    lines += ["    };", "    static final String[] HEX = {"]
    lines += [f"        \"{r['hex']}\"," for r in records]
    lines += ["    };", "}"]
    (out / "bridge" / "BridgeFixtures.java").write_text("\n".join(lines) + "\n", encoding="utf-8")
    for r in records:
        print(f"fixture {r['name']}: {r['bytes']} bytes")


if __name__ == "__main__":
    main()
