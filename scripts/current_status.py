#!/usr/bin/env python3
"""Render curated acceptance evidence beside source-derived patch identities."""
import argparse
import hashlib
import json
from pathlib import Path
from local_dev import PINNED

ROOT = Path(__file__).resolve().parent.parent
STATES = {'NOT IMPLEMENTED', 'IMPLEMENTED / AUTOMATED VALIDATION PASSED',
          'PHYSICAL ACCEPTANCE REQUIRED', 'PHYSICALLY ACCEPTED', 'DEFERRED'}


def render(root=ROOT):
    data = json.loads((root / 'docs/current-status.json').read_text())
    lines = ['# Current SoloScape status', '', '<!-- Generated by scripts/current_status.py; edit docs/current-status.json. -->', '',
             f"Reviewed {data['reviewed_on']} against merged baseline `{data['reviewed_base']}`.", '',
             'This is the current evidence index. Dated reports remain historical. A generated table does not turn automation into human acceptance; new claims require an evidence review.', '',
             '## Reproducible source', '', '| Upstream | Pinned commit |', '| --- | --- |']
    for name, pin in sorted(PINNED.items()):
        lines.append(f'| {name} | `{pin}` |')
    lines += ['', '| Stack | Patches | Last patch | SHA-256 of ordered names and bytes |', '| --- | ---: | --- | --- |']
    for stack in ('client', 'server'):
        files = sorted((root / 'patches' / stack).glob('*.patch'))
        if not files:
            raise ValueError('Missing patch stack: ' + stack)
        digest = hashlib.sha256()
        for path in files:
            digest.update(path.name.encode() + b'\0' + path.read_bytes() + b'\0')
        lines.append(f'| {stack} | {len(files)} | `{files[-1].name}` | `{digest.hexdigest()}` |')
    lines += ['', 'These are tracked source identities, not an installed-device inventory or proof of a matched jar. See build stamps and private device manifests for the latter.', '',
              '## Delivery and acceptance', '', '| Capability / scope | Delivery | Acceptance | Evidence / limit |', '| --- | --- | --- | --- |']
    seen = set()
    for row in data['entries']:
        if row['id'] in seen:
            raise ValueError('Duplicate capability: ' + row['id'])
        seen.add(row['id'])
        if row['delivery'] not in STATES or row['acceptance'] not in STATES:
            raise ValueError('Unknown evidence state')
        evidence = root / 'docs' / row['evidence']
        if not evidence.resolve().is_relative_to((root / 'docs').resolve()) or not evidence.is_file():
            raise ValueError('Missing/unsafe evidence: ' + row['evidence'])
        lines.append(f"| {row['scope']} | {row['delivery']} | {row['acceptance']} | [{row['note']}]({row['evidence']}) |")
    lines += ['', '## Decisions and maintenance', '',
              '- Start with [playtest direction](PLAYTEST_DIRECTION.md); use the GitHub human-playtest issue form.',
              '- Native 2010–2011 rules and Deck remain primary. [Backports](BACKPORT_ARCHITECTURE.md) and [WASM](WASM_FEASIBILITY.md) are bounded research tracks.',
              '- Edit the curated ledger when evidence changes, then run `python3 scripts/current_status.py`. CI runs `--check` to catch unregenerated changes and patch drift.',
              '- A maintainer must reassess affected acceptance rows when patches change. The generator cannot infer which UI regressions or human acceptances a patch invalidates.',
              '- Never rewrite a dated validation result to make it appear current. Link a new report with build, input method, renderer, power and limitations.', '']
    return '\n'.join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    options = parser.parse_args()
    output = ROOT / 'docs/CURRENT_STATUS.md'
    expected = render()
    if options.check:
        if not output.exists() or output.read_text() != expected:
            parser.exit(1, 'CURRENT_STATUS.md is stale; run python3 scripts/current_status.py\n')
    else:
        output.write_text(expected)


if __name__ == '__main__':
    main()
